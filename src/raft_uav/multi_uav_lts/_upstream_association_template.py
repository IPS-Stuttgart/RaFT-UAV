def env_bool(name, default):
    value = os.environ.get(name)
    if value is None:
        return bool(default)
    normalized = value.strip().lower()
    if normalized in {"1", "true", "yes", "on"}:
        return True
    if normalized in {"0", "false", "no", "off"}:
        return False
    raise ValueError(f"{name} must be a boolean, got {value!r}")


def env_int(name, default, minimum=None):
    value = int(os.environ.get(name, default))
    if minimum is not None and value < minimum:
        raise ValueError(f"{name} must be >= {minimum}, got {value}")
    return value


def env_float(name, default, minimum=None, maximum=None, *, strict_minimum=False):
    value = float(os.environ.get(name, default))
    if not math.isfinite(value):
        raise ValueError(f"{name} must be finite, got {value!r}")
    if minimum is not None:
        invalid = value <= minimum if strict_minimum else value < minimum
        if invalid:
            operator = ">" if strict_minimum else ">="
            raise ValueError(f"{name} must be {operator} {minimum}, got {value}")
    if maximum is not None and value > maximum:
        raise ValueError(f"{name} must be <= {maximum}, got {value}")
    return value


def env_float_list(name, default, *, minimum=None, maximum=None):
    raw = os.environ.get(name, default)
    values = []
    for item in str(raw).split(","):
        stripped = item.strip()
        if not stripped:
            raise ValueError(f"{name} contains an empty value")
        value = float(stripped)
        if not math.isfinite(value):
            raise ValueError(f"{name} must contain only finite values")
        if minimum is not None and value < minimum:
            raise ValueError(f"{name} values must be >= {minimum}")
        if maximum is not None and value > maximum:
            raise ValueError(f"{name} values must be <= {maximum}")
        values.append(value)
    if not values:
        raise ValueError(f"{name} must contain at least one value")
    if len(set(values)) != len(values):
        raise ValueError(f"{name} must not contain duplicate values")
    return tuple(values)


